"""Step 6 - results/ANALYSIS_REPORT.md, generated from results.json (+ the per-hypothesis test tables it writes).
Run through run_all.py; never edit the report by hand."""

from __future__ import annotations

import os

import pandas as pd

from common import RESULTS, save_table
from narrative import (R, dataset_block, dataset_ids, dataset_headline, ext_done, attrition_bias, attrition_paragraphs, headline, held_lists, ids_for, itt_changes, limitations,
                       load, n_text, not_justified, pct, result_paragraphs, robustness, test_rows)
from spec import SPEC

ORDER = list(SPEC)


def md_table(rows: list[dict]) -> str:
    if not rows:
        return "_No rows._"
    cols = list(rows[0])
    esc = lambda v: str(v).replace("|", "\\|").replace("\n", " ")  # noqa: E731
    out = ["| " + " | ".join(cols) + " |", "| " + " | ".join("---" for _ in cols) + " |"]
    out += ["| " + " | ".join(esc(r[c]) for c in cols) + " |" for r in rows]
    return "\n".join(out)


def scorecard_rows(r: R) -> list[dict]:
    rows = []
    for hid in ORDER:
        h, sp = r.hyps[hid], SPEC[hid]
        p = r.t(sp["primary"]) if sp.get("primary") else None
        if hid == "H9":
            res = "app: exploratory bias × gender model; " + (
                dataset_headline(r, hid) if ext_done(r, hid) else "dataset part pending")
            n = n_text(r.t("H9.app.la_group_x_male"))
            if ext_done(r, hid):
                n += f"; NFCS State {r.s['external_dataset']['state']['rows']:,}"
        elif hid == "H8" and ext_done(r, hid):
            res = f"App: {headline(p)}; {dataset_headline(r, hid)}"
            n = f"{n_text(p)}; NFCS Investor {r.t('H8.dataset')['n']['respondents']:,}"
        elif hid == "H1h":
            top = r.s["H1h_ux_map"][0]
            res, n = f"top feature: {top['feature']} {top['yes']}/{top['n']}", f"fraud {top['n']}"
        else:
            res = (p.get("test", "") + ": " + headline(p)) if p else "–"
            n = n_text(p)
        verdict = h["verdict"] + (f" ({h['label']})" if h.get("label") else "")
        rows.append({"Hyp.": hid, "Short": sp["short"], "Prediction": sp["prediction"], "Primary result": res,
                     "n": n, "Verdict": verdict})
    return rows


def write_tables(r: R) -> None:
    save_table(pd.DataFrame(scorecard_rows(r)), "scorecard")
    for hid in ORDER:
        save_table(pd.DataFrame(test_rows(r, ids_for(r, hid) + dataset_ids(r, hid))), f"tests_{hid}")


def build(r: R) -> str:
    m = r.meta
    L = []
    L.append(f"# Analysis Report — {m['title']}")
    L.append("")
    L.append(f"_Generated by `analysis/run_all.py` on {m['generated_at']} from the files in `data/`. Every number "
             "comes from `results/results.json` and `results/tables/`; do not edit by hand. Pre-registered plan: "
             "`results/ANALYSIS_PLAN.md`._")
    L.append("")
    L.append(f"App study: {m['consented']} consented players (honest {m['consented_by_skin']['honest']}, fraud "
             f"{m['consented_by_skin']['fraud']}), {m['completed']} completed (honest "
             f"{m['completed_by_skin']['honest']}, fraud {m['completed_by_skin']['fraud']}); collection "
             f"{m['collection_start']} to {m['collection_end']}. Survey: {r.s['survey']['respondents']} consenting "
             f"respondents ({r.s['survey']['first_response']} to {r.s['survey']['last_response']}). All tests "
             f"two-sided, α = {m['alpha']}; bootstrap CIs with {m['bootstrap']['resamples']:,} resamples (seed "
             f"{m['bootstrap']['seed']}).")
    L.append("")

    # 1. Scorecard
    L.append("## 1. Summary scorecard")
    L.append("")
    L.append("Verdict rules (pre-registered): SUPPORTED = primary outcome in the predicted direction with p < 0.05; "
             "PARTLY SUPPORTED = predicted direction with 0.05 ≤ p < 0.10, or most secondary outcomes significant in "
             "the predicted direction; NOT SUPPORTED = no difference or the opposite direction; NOT TESTABLE = no "
             "comparison or too little data; PENDING = needs the external dataset. Verdicts use raw p-values; "
             "Holm-adjusted p-values are reported in each section.")
    L.append("")
    L.append(md_table(scorecard_rows(r)))
    L.append("")
    L.append("Effect sizes: δ = Cliff's delta (−1 to 1; for a yes/no outcome it equals the difference in shares), "
             "OR = odds ratio, η²_Q = Cochran's Q effect size, b = regression coefficient; brackets = 95% CI.")
    L.append("")

    # 2. Data and attrition
    L.append("## 2. Data and attrition")
    L.append("")
    L.append("**Read this before any hypothesis result.**")
    L.append("")
    for p in attrition_paragraphs(r):
        L += [p, ""]
    L.append("![Drop-out funnel](figures/attrition_funnel.png)")
    L.append("")
    funnel = pd.read_csv(os.path.join(RESULTS, "tables", "attrition_funnel.csv"))
    L.append(md_table(funnel.rename(columns={"milestone": "Milestone", "step": "Step", "honest": "Honest reached",
                                             "fraud": "Fraud reached"}).to_dict("records")))
    L.append("")
    L.append("### What the attrition means for the H1 results")
    L.append("")
    L += attrition_bias(r) + [""]
    changes = itt_changes(r)
    L.append("**Intention-to-treat check (H1 and H2, everyone who reached the home screen):** " + (
        "conclusions change for " + "; ".join(changes) + "." if changes else "no conclusion changes.")
             + " Details are in the robustness notes of H1 and H2.")
    L.append("")

    # 3. Hypotheses
    L.append("## 3. Hypotheses")
    L.append("")
    for hid in ORDER:
        sp, h = SPEC[hid], r.hyps[hid]
        L.append(f"### {hid} — {sp['title']}")
        L.append("")
        L.append(f"**Verdict: {h['verdict']}**" + (f" ({h['label']})" if h.get("label") else "")
                 + f" — {h['verdict_reason']}.")
        L.append("")
        L.append(f"**What we claimed.** {sp['claim']}")
        L.append("")
        L.append(f"**How the experiment tests it.** {sp['how']}")
        L.append("")
        L.append("**The maths.**")
        L.append("")
        L += ["```text", sp["maths"], "```", ""]
        L.append("**Result.**")
        L.append("")
        for p in result_paragraphs(r, hid):
            L += [p, ""]
        for f in dict.fromkeys(sp["figures"]):
            L += [f"![{hid}](figures/{f}.png)", ""]
        rows = test_rows(r, ids_for(r, hid))
        if rows:
            L += [md_table(rows), ""]
        for kind, item in dataset_block(r, hid):
            if kind == "h":
                L += [f"#### {item}", ""]
            elif kind == "p":
                L += [item, ""]
            elif kind == "list":
                L += [x if x.startswith("- ") else f"- {x}" for x in item] + [""]
            elif kind == "table":
                L += [md_table(item), ""]
            elif kind == "fig":
                L += [f"![{hid} dataset](figures/{item}.png)", ""]
        L.append("**Verdict and what the data does NOT justify.**")
        L.append("")
        L += [f"- {x}" for x in not_justified(r, hid)] + [""]
        rob = robustness(r, hid)
        if rob:
            L.append("**Robustness notes.**")
            L.append("")
            L += [f"  {x}" if x.startswith("- ") else f"- {x}" for x in rob] + [""]
        if hid in ("H8", "H9"):
            ext = r.s["external"][hid]
            if ext.get("status") != "done":
                L += [f"**Dataset part: PENDING** — {ext.get('reason')}. Add the dataset and fill "
                      "`analysis/external_config.yaml` (see `data/external/README.md`); `run_all.py` then fills this "
                      "part in.", ""]

    # 4. Survey
    sv = r.s["survey"]
    L.append("## 4. Survey: real-life evidence")
    L.append("")
    a = sv["approached"]
    L.append(f"Descriptive only (no randomization, not linked to the app players). {sv['respondents']} consenting "
             f"respondents; {sv['non_consenting_dropped']} non-consenting row dropped. Approached by a suspicious "
             f"investment or earning app/group: {a['yes']} of {a['n']} who answered yes or no ({pct(a['share'])}, "
             f"95% CI {pct(a['ci_low'])}–{pct(a['ci_high'])}); "
             f"{sv['q1_counts'].get('Not sure', 0)} were not sure. Of those approached, "
             f"{sv['approached_past_12m']['yes']} of {sv['approached_past_12m']['n']} said it happened in the past "
             "12 months.")
    L.append("")
    L.append("![Tricks seen](figures/survey_tricks_seen.png)")
    L.append("")
    L.append(md_table([{"Trick": t["trick"], "Seen": f"{t['yes']}/{t['n']}", "Share [95% CI]":
                        f"{pct(t['share'])} [{pct(t['ci_low'])}, {pct(t['ci_high'])}]"} for t in sv["tricks_seen"]]))
    L.append("")
    L.append("**How approached respondents were first contacted:** " + "; ".join(
        f"{c['channel']} {c['yes']}/{c['n']}" for c in sv["channels"]) + ".")
    L.append("")
    ws = sv["what_stopped_answered"]
    L.append(f"**What stopped them from putting money in** ({ws['answered']} of {ws['of_non_investors']} approached "
             "non-investors answered; several reasons allowed):")
    L.append("")
    L.append("![What stopped them](figures/survey_what_stopped.png)")
    L.append("")
    L.append(md_table([{"Reason": t["reason"], "Count": f"{t['yes']}/{t['n']}", "Share [95% CI]":
                        f"{pct(t['share'])} [{pct(t['ci_low'])}, {pct(t['ci_high'])}]"} for t in sv["what_stopped"]]))
    L.append("")
    ic = sv["invested_count"]
    L.append(f"**Respondents who put money in: {ic['yes']} of {ic['of']} approached.** Too few for percentages or "
             "tests; counts only:")
    L.append("")
    L.append(md_table([{"Question": x["question"], "Item": x["item"],
                        "Answers": (f"yes {x['yes']} of {x['of_invested']}, no {x['no']}, don't remember/blank "
                                    f"{x['dont_remember_or_blank']}" if x["question"] != "Q11" else x["bands"])}
                       for x in sv["invested_items"]]))
    L.append("")
    L.append("**Common in real life vs persuasive in the app.** For the seven features both instruments measure: the "
             "share of survey respondents who have seen the trick, next to the share of fraud-skin players who said "
             "it pushed them to invest. Different people and different questions; read it as a map, not a test.")
    L.append("")
    L.append("![Survey vs app](figures/survey_vs_app.png)")
    L.append("")
    L.append(md_table([{"Feature": c["feature"], "Seen in real life (survey)":
                        f"{c['survey_yes']}/{c['survey_n']} ({pct(c['survey_seen_share'])})",
                        "Pushed them (app, fraud)": f"{c['app_yes']}/{c['app_n']} ({pct(c['app_pushed_share'])})"}
                       for c in sv["survey_vs_app"]]))
    L.append("")

    # 5. Held / not
    held, not_held, other = held_lists(r)
    L.append("## 5. What held, what did not")
    L.append("")
    L.append("**Held (supported or partly supported):**")
    L.append("")
    L += [f"- {x}" for x in held] or ["- none"]
    L.append("")
    L.append("**Did not hold (not supported):**")
    L.append("")
    L += [f"- {x}" for x in not_held] or ["- none"]
    L.append("")
    L.append("**No verdict possible yet / by design:**")
    L.append("")
    L += [f"- {x}" for x in other] or ["- none"]
    L.append("")

    # 6. Limitations
    L.append("## 6. Limitations")
    L.append("")
    L += [f"- {x}" for x in limitations(r)]
    L.append("")
    if r.d.get("problems"):
        L.append("## Problems recorded during the analysis")
        L.append("")
        L += [f"- {x}" for x in r.d["problems"]]
        L.append("")
    return "\n".join(L)


def run() -> str:
    r = R(load())
    write_tables(r)
    path = os.path.join(RESULTS, "ANALYSIS_REPORT.md")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(build(r))
    return path
