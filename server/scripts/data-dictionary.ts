/**
 * Writes docs/data-dictionary.md from the wide.csv column definitions in src/wide.ts,
 * so the documentation always matches the export. Run: npm run docs:dictionary
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { wideColumns, type Column } from '../src/wide';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const out = path.join(root, 'docs', 'data-dictionary.md');

const esc = (s: string) => s.replace(/\|/g, '\\|');

export function renderDictionary(): string {
  const cols = wideColumns();
  const groups: Column['group'][] = [
    'Identifiers & assignments',
    'App behaviour (event log)',
    'Survey items',
    'Derived scores',
  ];
  const lines = [
    '# Data dictionary — `wide.csv`',
    '',
    '<!-- Generated by `npm run docs:dictionary` from server/src/wide.ts. Do not edit by hand. -->',
    '',
    'One row per participant who **completed** the general survey and did **not withdraw** their data.',
    'Download it from `/admin` → wide.csv. Yes/no columns use `1` = yes, `0` = no; a blank cell means',
    '"not applicable" or "not answered". Amounts are in virtual ₹.',
    '',
    `Total columns: ${cols.length}.`,
    '',
    '**Other exports** (raw, for checking): `participants.csv` (one row per consented participant),',
    '`events.csv` (append-only behaviour log: `ts` = server time in ms, `client_ts` = ms since page load,',
    '`screen`, `event_type`, `payload` JSON) and `responses.csv` (one row per participant × item).',
    'Withdrawn participants are excluded from all four files; pilot participants are included and',
    'flagged with `is_pilot = 1`.',
    '',
  ];
  for (const g of groups) {
    lines.push(`## ${g}`, '', '| Column | Description | Hypotheses |', '| --- | --- | --- |');
    for (const c of cols.filter((x) => x.group === g)) {
      lines.push(`| \`${c.name}\` | ${esc(c.description)} | ${esc(c.hypotheses)} |`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, renderDictionary());
  console.log(`Wrote ${path.relative(root, out)}`);
}
